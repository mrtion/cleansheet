## 乱码的真正原因：UTF-8 vs GBK

Amazon 导出的是 **UTF-8 编码**的 CSV，而中文版 Excel/WPS 默认按 **GBK** 解码。同一个字节序列，用两种编码去读，中文就变成了乱码。英文、数字不受影响，所以你会看到「订单号正常、中文全乱」这个典型症状。解决思路就一条：**让「写」和「读」用同一种编码**。

## 解法 1：Excel 数据导入向导（手动，2 分钟）

1. 新建一个空白工作簿 → **数据**选项卡 → **从文本/CSV 获取数据**。
2. 选中下载的结算 CSV，在导入对话框里把「文件原始格式」改为 **65001: Unicode (UTF-8)**。
3. 预览里中文正常显示后点「加载」，完成。

优点：不用装任何东西。缺点：每个文件都要走一遍向导，店铺多了很烦。

## 解法 2：记事本另存转码（手动，1 分钟）

1. 右键 CSV → 用**记事本**打开（中文应该正常显示）。
2. **文件 → 另存为**，编码选择 **ANSI**（即 GBK）。
3. 保存后双击用 Excel 打开，中文正常。

