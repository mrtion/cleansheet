## 第 3 步：币种换算，统一成人民币

美区是 USD、英区是 GBP、日区是 JPY，直接相加没有意义。在清洗时开启**汇率换算**，按统一的月度汇率把「销售额」折成人民币新增一列。建议全公司用同一套月度汇率（比如央行中间价月均值），财务、运营口径一致，月底对数才不会吵架。

## 第 4 步：去重，再合并

